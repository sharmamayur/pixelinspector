// Returns 'standard', 'custom', or null when the vendor has no standard event list.
export function standardEventType(platform, name) {
  const catalog = events[platform];
  if (!catalog || typeof name !== 'string') return null;
  const standard = catalog.test ? catalog.test(name)
    : catalog.ignoreCase ? catalog.names.includes(name.toLowerCase()) : catalog.names.includes(name);
  return standard ? 'standard' : 'custom';
}


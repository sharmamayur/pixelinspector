// The parameter name inside a vendor's event-data namespace, or null for transport and
// identity fields outside it.
function fieldKey(platform, name) {
  const text = String(name);
  const strip = key => key?.replace(/\[\d+\]$/, '') ?? null;
  switch (platform) {
    case 'Meta': return text.match(/^cd\[([^\]]+)\]/)?.[1] ?? null;
    case 'GA4': return /^pr\d+$/.test(text) ? 'items' : text === 'cu' ? 'currency' : text.match(/^epn?\.(.+)$/)?.[1] ?? null;
    case 'TikTok': return strip(text.match(/(?:^|\.)properties\.([^.[]+(?:\[\d+\])?)/)?.[1]);
    case 'Pinterest': return text.match(/^ed\[([^\]]+)\]/)?.[1] ?? null;
    case 'Snapchat': return strip(text.match(/(?:^|\.t\.)([a-z_]+(?:\[\d+\])?)$/)?.[1]);
    case 'Reddit Ads': return text.match(/^(?:event_metadata\.)?([^.[]+)/)?.[1] ?? null;
    default: return text;
  }
}

export function isStandardField(platform, name) {
  const standard = fields[platform];
  const key = fieldKey(platform, name);
  if (!standard || !key) return false;
  return typeof standard === 'function' ? standard(key) : standard.includes(key);
}
